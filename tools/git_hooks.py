"""Install the repository's pinned native Git hook engine."""

from __future__ import annotations

import argparse
import base64
import fcntl
import hashlib
import os
import re
import shlex
import stat
import subprocess
import sys
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from importlib.metadata import distribution
from pathlib import Path

VERSION = "0.5.5"
STAGES = ("pre-commit", "pre-push")
NATIVE_MARKER = b"# ID: 182c10f181da4464a3eec51b83331688"
MAX_PACKET_BYTES = 1024 * 1024


def git(*args: str) -> str:
    return os.fsdecode(subprocess.check_output(["git", *args]).removesuffix(b"\n"))


def native_executable() -> Path:
    package = distribution("prek")
    if package.version != VERSION:
        raise ValueError(f"Install development requirements: prek=={VERSION} is required")
    binaries = [f for f in package.files or () if f.name == "prek"]
    if len(binaries) != 1:
        raise ValueError("Installed prek native executable is missing or ambiguous")
    entry = binaries[0]
    binary = Path(package.locate_file(entry)).resolve()
    digest = base64.urlsafe_b64encode(hashlib.sha256(binary.read_bytes()).digest()).decode().rstrip("=")
    if not entry.hash or entry.hash.mode != "sha256" or digest != entry.hash.value:
        raise ValueError("Installed prek executable does not match its package RECORD")
    if not os.access(binary, os.X_OK):
        raise ValueError("Installed prek executable is not executable")
    return binary


def hook_files(hooks: Path) -> list[Path]:
    return [hooks / (stage + suffix) for stage in STAGES for suffix in ("", ".legacy")]


def owned_directory(path: Path) -> None:
    if not path.exists() and not path.is_symlink():
        return
    info = path.lstat()
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid():
        raise ValueError(f"Refusing non-directory or foreign-owned hook directory: {path}")


def preflight(hooks: Path, state: Path) -> dict[Path, tuple[int, bytes] | None]:
    owned_directory(hooks)
    owned_directory(state)
    before = {p: snapshot(p) for p in hook_files(hooks)}
    for stage in STAGES:
        current = before[hooks / stage]
        if current and NATIVE_MARKER not in current[1] and before[hooks / (stage + ".legacy")]:
            raise ValueError(f"Foreign {stage} and existing legacy hook require manual reconciliation")
    return before


def snapshot(path: Path) -> tuple[int, bytes] | None:
    if not path.exists() and not path.is_symlink():
        return None
    mode = path.lstat().st_mode
    if not stat.S_ISREG(mode) or path.lstat().st_uid != os.getuid():
        raise ValueError(f"Refusing nonregular or foreign-owned hook state: {path}")
    return stat.S_IMODE(mode), path.read_bytes()


def atomic_write(path: Path, data: bytes, mode: int) -> None:
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as output:
        temporary = Path(output.name)
        output.write(data)
        output.flush()
        os.fchmod(output.fileno(), mode)
        os.fsync(output.fileno())
    temporary.replace(path)


def guarded_shim(state: Path, stage: str, hooks: Path) -> bytes:
    command = shlex.join(["python3", str(state / "guard.py"), "hook", stage, str(hooks), "--"])
    return (
        "#!/bin/sh\n"
        "# File generated by prek: https://github.com/j178/prek\n"
        "# ID: 182c10f181da4464a3eec51b83331688\n"
        f'exec {command} "$@"\n'
    ).encode()


@contextmanager
def installation_lock(common: Path) -> Iterator[None]:
    flags = os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW | os.O_CLOEXEC
    descriptor = os.open(common / "agent-skills-hooks.lock", flags, 0o600)
    with os.fdopen(descriptor, "r+") as owner:
        info = os.fstat(owner.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid():
            raise ValueError("Refusing a nonregular or foreign-owned installation lock")
        try:
            fcntl.flock(owner, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise ValueError("Another Git hook installation is active") from exc
        yield


def install_native_hooks(binary: Path, common: Path, hooks: Path) -> None:
    state = common / "agent-skills-hooks"
    before = preflight(hooks, state)
    state_before = {state / name: snapshot(state / name) for name in ("prek", "prek.sha256", "guard.py")}
    with tempfile.TemporaryDirectory(prefix="hook-stage-", dir=common) as directory:
        staged = Path(directory)
        target = staged / "hooks"
        target.mkdir()
        for path, previous in before.items():
            if previous:
                atomic_write(target / path.name, previous[1], previous[0])
        args = [str(binary), "install", "--git-dir", str(staged)]
        for stage in STAGES:
            args.extend(["--hook-type", stage])
        subprocess.run(args, check=True)
        if before != preflight(hooks, state) or state_before != {p: snapshot(p) for p in state_before}:
            raise ValueError("Hooks changed during installation; nothing was published")
        state.mkdir(mode=0o700, exist_ok=True)
        binary_bytes = binary.read_bytes()
        atomic_write(state / "prek", binary_bytes, 0o700)
        atomic_write(state / "prek.sha256", hashlib.sha256(binary_bytes).hexdigest().encode(), 0o600)
        atomic_write(state / "guard.py", Path(__file__).read_bytes(), 0o600)
        hooks.mkdir(exist_ok=True)
        for stage in STAGES:
            legacy = target / (stage + ".legacy")
            if legacy.exists():
                atomic_write(hooks / legacy.name, legacy.read_bytes(), stat.S_IMODE(legacy.stat().st_mode))
            atomic_write(hooks / stage, guarded_shim(state, stage, hooks), 0o700)
    print(f"Installed prek {VERSION} pre-commit and pre-push hooks")


def install() -> None:
    binary = native_executable()
    common = Path(git("rev-parse", "--path-format=absolute", "--git-common-dir"))
    hooks = Path(git("rev-parse", "--path-format=absolute", "--git-path", "hooks"))
    with installation_lock(common):
        install_native_hooks(binary, common, hooks)


def parse_push_row(row: bytes, head: str) -> tuple[str, str, str, str]:
    match = re.fullmatch(rb"([^\s]+) ([0-9a-f]+) ([^\s]+) ([0-9a-f]+)", row)
    if not match:
        raise ValueError("Malformed pre-push row; expected four literal-space-separated fields")
    local_ref, local_oid, remote_ref, remote_oid = (value.decode() for value in match.groups())
    if len(local_oid) != len(head) or len(remote_oid) != len(head):
        raise ValueError("Malformed pre-push object identity")
    ref = subprocess.run(["git", "check-ref-format", remote_ref], capture_output=True, check=False)
    if ref.returncode:
        raise ValueError("Malformed pre-push destination")
    return local_ref, local_oid, remote_ref, remote_oid


def validate_source(local_ref: str, local_oid: str, remote_ref: str, head: str) -> None:
    if not remote_ref.startswith("refs/heads/"):
        raise ValueError("Only branch source updates are supported")
    if local_ref != "HEAD" and not local_ref.startswith("refs/heads/"):
        raise ValueError("Only checked-out branch or HEAD sources are supported")
    if local_oid != head or git("rev-parse", "--verify", local_ref + "^{commit}") != local_oid:
        raise ValueError("Pre-push source differs from checked-out HEAD")


def validate_push(args: list[str], packet: bytes) -> None:
    if len(args) != 2:
        raise ValueError("Pre-push requires Git's original remote arguments")
    if len(packet) > MAX_PACKET_BYTES or b"\0" in packet:
        raise ValueError("Pre-push input exceeds 1 MiB or contains NUL")
    head = git("rev-parse", "--verify", "HEAD")
    zero = "0" * len(head)
    rows = packet.split(b"\n")
    if rows[-1] == b"":
        rows.pop()
    sources = 0
    for row in rows:
        local_ref, local_oid, remote_ref, remote_oid = parse_push_row(row, head)
        if local_oid == zero:
            if local_ref != "(delete)" or remote_oid == zero:
                raise ValueError("Malformed pre-push deletion row")
            continue
        sources += 1
        if sources > 1:
            raise ValueError("Push one checked-out source branch at a time")
        validate_source(local_ref, local_oid, remote_ref, head)
    if sources and git("status", "--porcelain", "--untracked-files=normal"):
        raise ValueError("Source push requires a clean checkout of the declared HEAD")


def hook(stage: str, hooks: Path, args: list[str]) -> None:
    state = Path(__file__).parent
    pin = state / "prek"
    try:
        expected = (state / "prek.sha256").read_text()
        if not re.fullmatch(r"[0-9a-f]{64}", expected):
            raise ValueError("Invalid pinned prek digest")
        if not stat.S_ISREG(pin.lstat().st_mode) or not os.access(pin, os.X_OK):
            raise ValueError("Missing executable pinned prek")
        if hashlib.sha256(pin.read_bytes()).hexdigest() != expected:
            raise ValueError("Changed pinned prek executable")
    except OSError as exc:
        raise ValueError("Missing pinned prek executable or digest") from exc
    os.chdir(git("rev-parse", "--show-toplevel"))
    if stage == "pre-push":
        packet = sys.stdin.buffer.read(MAX_PACKET_BYTES + 1)
        validate_push(args, packet)
        # Native prek and any migrated legacy hook consume the original bytes.
        with tempfile.TemporaryFile() as original:
            original.write(packet)
            original.seek(0)
            os.dup2(original.fileno(), 0)
    os.execv(
        str(pin),
        [
            str(pin),
            "hook-impl",
            "--hook-dir",
            str(hooks),
            "--script-version",
            "4",
            f"--hook-type={stage}",
            "--config=.pre-commit-config.yaml",
            "--",
            *args,
        ],
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("install")
    runtime = commands.add_parser("hook")
    runtime.add_argument("stage", choices=STAGES)
    runtime.add_argument("hooks", type=Path)
    runtime.add_argument("args", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    try:
        if args.command == "install":
            install()
        else:
            hook(args.stage, args.hooks, args.args[1:] if args.args[:1] == ["--"] else args.args)
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f"Hook configuration error: {exc}\n")


if __name__ == "__main__":
    main()
